# 6. service worker: precache the app and every destination's content; map files are saved by the app itself
files = sorted('./' + p.relative_to(OUT).as_posix() for p in OUT.rglob('*')
               if p.is_file() and p.name not in ('sw.js', 'LICENSE', 'LICENSE.txt') and p.suffix != '.pmtiles')
files = ['./'] + files
(OUT / 'sw.js').write_text(f'''/* Wanderings offline support. One app. Version {version} */
const CACHE = 'wanderings-app-{version}';
const FILES = {json.dumps(files)};
self.addEventListener('install', e => {{
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES.map(f => new Request(f, {{ cache: 'reload' }})))).catch(() => {{}}));
  self.skipWaiting();
}});
self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE && k.startsWith('wanderings-app-')).map(k => caches.delete(k)))));
  self.clients.claim();
}});
self.addEventListener('fetch', e => {{
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.hostname.endsWith('tile.openstreetmap.org') || url.hostname === 'api.frankfurter.dev' || url.pathname.endsWith('.pmtiles')) return;
  const scope = new URL(self.registration.scope);
  if (!(url.origin === location.origin && url.pathname.startsWith(scope.pathname))) return;
  e.respondWith(fetch(req).then(r => {{
    if (r.ok) {{ const c = r.clone(); caches.open(CACHE).then(ca => ca.put(req, c)); }}
    return r;
  }}).catch(() => caches.match(req, {{ ignoreSearch: true }}).then(hit => hit || (req.mode === 'navigate' ? caches.match('./index.html') : undefined))));
}});
''')

